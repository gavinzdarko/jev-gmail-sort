// Writes extension/secrets.js (gitignored) from .env so the unpacked extension can run without a
// sign-in flow: a read-only Gmail refresh token, the Jev key and (optional) an OpenAI key for sort ideas. Temporary until "Sign in with Google".
//   bun run scripts/secrets.ts
const cred = await Bun.file(process.env.GOOGLE_TOKEN_FILE!).json();
const out = {
  google: { client_id: cred.client_id, client_secret: cred.client_secret, refresh_token: cred.refresh_token, token_uri: cred.token_uri || "https://oauth2.googleapis.com/token" },
  jevKey: process.env.TYPESAFE_API_KEY,
  openaiKey: process.env.OPENAI_API_KEY || "",
};
await Bun.write("extension/secrets.js", `// Generated by scripts/secrets.ts. Never commit this file.\nexport default ${JSON.stringify(out, null, 2)};\n`);
console.log("wrote extension/secrets.js");
